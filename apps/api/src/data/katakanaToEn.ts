// TCG card name suffixes in Japanese that map 1:1 to English
const JP_SUFFIXES: [RegExp, string][] = [
  [/VMAX$/, 'VMAX'],
  [/VSTAR$/, 'VSTAR'],
  [/\bV$/, 'V'],
  [/ex$/, 'ex'],
  [/EX$/, 'EX'],
  [/GX$/, 'GX'],
  [/BREAK$/, 'BREAK'],
  [/△$/, 'Prism Star'],
  [/LV\.X$/, 'LV.X'],
  [/ TAG TEAM$/, ''],
];

/**
 * Given a JP card name, extract the EN equivalent using the species dictionary.
 * Returns null if no match found.
 * Examples:
 *   "ピカチュウV"  → "Pikachu V"
 *   "リザードンex" → "Charizard ex"
 *   "ミュウツー"   → "Mewtwo"
 */
export function jpNameToEn(jpName: string): string | null {
  // Try direct lookup first
  const direct = KATAKANA_TO_EN[jpName];
  if (direct) return direct;

  // Strip common TCG suffixes and try again
  let base = jpName;
  let suffix = '';
  for (const [pattern, engSuffix] of JP_SUFFIXES) {
    if (pattern.test(base)) {
      base = base.replace(pattern, '').trim();
      suffix = engSuffix ? ` ${engSuffix}` : '';
      break;
    }
  }

  const enBase = KATAKANA_TO_EN[base];
  if (enBase) return `${enBase}${suffix}`;

  return null;
}
